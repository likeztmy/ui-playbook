// Generates src/styles/tokens.css from src/tokens/precision.json.
// The JSON uses the Precision design-system list shape: every family is
// { tokens: [{ name, value }] }, where a themed value is { light, dark }.
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../src/tokens/precision.json', import.meta.url);
const out = new URL('../src/styles/tokens.css', import.meta.url);
const t = JSON.parse(readFileSync(src, 'utf8'));

const themes = t.color.themes.map((th) => th.id);
const [primary] = themes;
const vars = Object.fromEntries(themes.map((id) => [id, []]));
const plain = [];

// An alias such as "{accent-text}" resolves per theme block: declared once on
// :root, var() would compute there and nested [data-theme] subtrees would
// inherit the root theme's value.
const alias = (v) => typeof v === 'string' && /^\{[A-Za-z0-9_.-]+\}$/.test(v);

function push(name, value) {
  if (alias(value)) {
    for (const id of themes) vars[id].push(`  --${name}: var(--${value.slice(1, -1)});`);
  } else if (value && typeof value === 'object') {
    for (const id of themes) vars[id].push(`  --${name}: ${value[id] ?? value[primary]};`);
  } else {
    plain.push(`  --${name}: ${value};`);
  }
}

for (const [family, group] of Object.entries(t)) {
  if (family === 'type' || !group?.tokens) continue;
  for (const tok of group.tokens) push(tok.name, tok.value);
}
// The design system names faces as designers know them; the self-hosted
// fontsource packages register them under other names. Lead each stack with
// the registered name so precision.json can be copied from the design
// system verbatim.
const SELF_HOSTED = { Geist: 'Geist Variable', 'Geist Mono': 'Geist Mono Variable' };
const leadSelfHosted = (stack) => {
  const first = stack.split(',')[0].trim().replace(/^"|"$/g, '');
  return SELF_HOSTED[first] ? `"${SELF_HOSTED[first]}", ${stack}` : stack;
};
for (const [name, stack] of Object.entries(t.type.families)) plain.push(`  --font-${name}: ${leadSelfHosted(stack)};`);

const typeClasses = t.type.groups.flatMap((g) =>
  g.styles.map((s) =>
    [
      `.type-${s.name} {`,
      `  font-family: var(--font-${g.family});`,
      `  font-size: ${s.fontSize};`,
      `  line-height: ${s.lineHeight};`,
      `  font-weight: ${s.fontWeight};`,
      s.letterSpacing ? `  letter-spacing: ${s.letterSpacing};` : null,
      '}',
    ]
      .filter(Boolean)
      .join('\n'),
  ),
);

const block = (sel, lines) => `${sel} {\n${lines.join('\n')}\n}`;

// A palette is a whole colour system laid over the default one: its own values for any colour
// token, per theme. It's chosen by [data-palette] on <html>; a subtree pinned to a theme by
// [data-theme] keeps the palette, in that theme. The first palette is the default and has no
// attribute.
const palettes = t.color.palettes ?? [];
const paletteVars = (p, id) =>
  Object.entries(p.values).map(([name, v]) => `  --${name}: ${typeof v === 'object' ? (v[id] ?? v[primary]) : v};`);
const paletteBlocks = palettes.slice(1).flatMap((p) => {
  const at = `[data-palette="${p.id}"]`;
  return [
    block(`:root${at}, ${at} [data-theme="${primary}"]`, paletteVars(p, primary)),
    ...themes
      .filter((id) => id !== primary)
      .flatMap((id) => [
        `@media (prefers-color-scheme: ${id}) {\n${block(`  :root${at}:not([data-theme])`, paletteVars(p, id).map((l) => '  ' + l)).replace(/\n}$/, '\n  }')}\n}`,
        block(`:root${at}[data-theme="${id}"], ${at} [data-theme="${id}"]`, paletteVars(p, id)),
      ]),
  ];
});

// A palette whose accent is the ink has no hue to teach colour with. Under it, a subtree marked
// [data-hued] (a page about colour) takes the default palette's values back, in either theme.
const base = Object.fromEntries(themes.map((id) => [id, Object.fromEntries(vars[id].map((l) => l.trim().slice(2, -1).split(': ')))]));
const monochrome = palettes.slice(1).filter((p) => (p.values.accent?.[primary] ?? p.values.accent) === base[primary].ink);
const restore = (p, id) => Object.keys(p.values).map((name) => `  --${name}: ${base[id][name]};`);
const huedBlocks = monochrome.flatMap((p) => {
  const at = `[data-palette="${p.id}"]`;
  const hued = (id) => `${at} [data-theme="${id}"] [data-hued], ${at} [data-hued] [data-theme="${id}"]`;
  return [
    block(`:root${at} [data-hued], ${hued(primary)}`, restore(p, primary)),
    ...themes
      .filter((id) => id !== primary)
      .flatMap((id) => [
        `@media (prefers-color-scheme: ${id}) {\n${block(`  :root${at}:not([data-theme]) [data-hued]`, restore(p, id).map((l) => '  ' + l)).replace(/\n}$/, '\n  }')}\n}`,
        block(`:root${at}[data-theme="${id}"] [data-hued], ${hued(id)}`, restore(p, id)),
      ]),
  ];
});

// A [data-theme] attribute pins a subtree to one theme; without it the
// document follows the system setting.
const css = [
  `/* Generated by scripts/build-tokens.mjs from src/tokens/precision.json. Do not edit. */`,
  block(':root', plain),
  block(`:root, [data-theme="${primary}"]`, [`  color-scheme: ${primary};`, ...vars[primary]]),
  ...themes
    .filter((id) => id !== primary)
    .flatMap((id) => [
      `@media (prefers-color-scheme: ${id}) {\n${block(`  :root:not([data-theme])`, [`  color-scheme: ${id};`, ...vars[id]].map((l) => '  ' + l)).replace(/\n}$/, '\n  }')}\n}`,
      block(`[data-theme="${id}"]`, [`  color-scheme: ${id};`, ...vars[id]]),
    ]),
  ...paletteBlocks,
  ...huedBlocks,
  ...typeClasses,
].join('\n\n');

writeFileSync(out, css + '\n');

// The picker's list: each palette's name and the colours its swatch is drawn in.
const list = palettes.map((p) => ({
  id: p.id,
  name: p.name,
  swatch: Object.fromEntries(themes.map((id) => [id, p.values.accent?.[id] ?? p.values.accent ?? null])),
}));
writeFileSync(
  new URL('../src/tokens/palettes.ts', import.meta.url),
  `// Generated by scripts/build-tokens.mjs from src/tokens/precision.json. Do not edit.\n\nexport const PALETTES = ${JSON.stringify(list, null, 2)} as const;\n\nexport type PaletteId = (typeof PALETTES)[number]['id'];\n`,
);
console.log(`tokens.css: ${plain.length + vars[primary].length} variables, ${palettes.length} palettes, ${typeClasses.length} type styles`);
